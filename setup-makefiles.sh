#!/bin/bash
# Regenerates Android.bp/Android.mk/a02q-vendor.mk for the a02q blobs.
set -e

DEVICE=a02q
VENDOR=samsung

MY_DIR="${BASH_SOURCE%/*}"
[ ! -d "$MY_DIR" ] && MY_DIR="$PWD"
ANDROID_ROOT="$MY_DIR/../../.."

HELPER="$ANDROID_ROOT/tools/extract-utils/extract_utils.sh"
[ -f "$HELPER" ] || { echo "Helper não encontrado em $HELPER"; exit 1; }
source "$HELPER"

setup_vendor "$DEVICE" "$VENDOR" "$ANDROID_ROOT" false

write_headers
write_makefiles "$MY_DIR/proprietary-files.txt" true
write_footers

# Dolby blobs live in a separate, untracked list and makefile (device.mk
# inherits it only if present).
DOLBY_LIST="$MY_DIR/proprietary-files-dolby.txt"
DOLBY_MK="$ANDROID_ROOT/vendor/$VENDOR/$DEVICE/dolby.mk"
if [ -f "$DOLBY_LIST" ]; then
    {
        echo "# Automatically generated by device/$VENDOR/$DEVICE/setup-makefiles.sh"
        echo "# from proprietary-files-dolby.txt. Not under version control."
        echo
        echo "PRODUCT_COPY_FILES += \\"
        grep -vE '^\s*(#|$)' "$DOLBY_LIST" | sed -E \
            "s#^vendor/(.*)\$#    vendor/$VENDOR/$DEVICE/proprietary/vendor/\1:\$(TARGET_COPY_OUT_VENDOR)/\1 \\\\#"
        echo
    } > "$DOLBY_MK"
else
    rm -f "$DOLBY_MK"
fi
